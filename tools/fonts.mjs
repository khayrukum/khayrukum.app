#!/usr/bin/env node
// @font-face rules for the self-hosted fonts (NFR-TYP-01, NFR-PERF-05). Only files that exist get a rule,
// so a missing font never causes a 404; the system fallbacks in app.css apply instead.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const FACES = [
  ['Reem Kufi', '400 700', 'reem-kufi-vf.woff2'], // variable font: one file covers every weight
  ['IBM Plex Sans Arabic', 400, 'ibm-plex-sans-arabic-400.woff2'], ['IBM Plex Sans Arabic', 500, 'ibm-plex-sans-arabic-500.woff2'], ['IBM Plex Sans Arabic', 600, 'ibm-plex-sans-arabic-600.woff2'],
  ['Amiri', 400, 'amiri-400.woff2'], ['Amiri', 700, 'amiri-700.woff2'],
  ['Amiri Quran', 400, 'amiri-quran-400.woff2']
];

export function fontsCss(dir) {
  const missing = []; let css = '/* Generated by tools/fonts.mjs. Self-hosted, OFL-licensed fonts (licenses in assets/fonts/LICENSES/). */\n';
  for (const [family, weight, file] of FACES) {
    if (!fs.existsSync(path.join(dir, file))) { missing.push(file); continue; }
    css += `@font-face { font-family: "${family}"; font-style: normal; font-weight: ${weight}; font-display: swap; src: url("../fonts/${file}") format("woff2"); }\n`;
  }
  return { css, missing };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const site = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../site');
  const { css, missing } = fontsCss(path.join(site, 'assets/fonts'));
  fs.writeFileSync(path.join(site, 'assets/css/fonts.css'), css);
  console.log(missing.length ? 'missing: ' + missing.join(', ') : 'all fonts present');
}
